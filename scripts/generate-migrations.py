#!/usr/bin/env python3
"""Regenerate src/storage/migrations/bundle.ts from the drizzle migrations folder.

The SQL is inlined as a template literal so that:
  - standalone Bun binaries work without a filesystem, and
  - Vitest / bundlers never try to parse a .sql file as JavaScript.

Run after `bun run db:generate`. Wired into `prebuild`.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "src" / "storage" / "migrations"


def ts_escape(sql: str) -> str:
    # Template literal: escape backslash, backtick, and ${ ...
    return (
        sql.replace("\\", "\\\\")
        .replace("`", "\\`")
        .replace("${", "\\${")
    )


def main() -> None:
    journal_path = MIGRATIONS / "meta" / "_journal.json"
    if not journal_path.exists():
        print("no journal found; nothing to bundle")
        return

    journal = json.loads(journal_path.read_text(encoding="utf-8"))
    entries = sorted(journal["entries"], key=lambda e: e["idx"])

    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/generate-migrations.py -- DO NOT EDIT BY HAND.")
    lines.append("// Migration SQL is inlined so standalone binaries and Vitest both work.")
    lines.append("")
    lines.append("export interface ManifestEntry {")
    lines.append("  idx: number")
    lines.append("  tag: string")
    lines.append("  sql: string")
    lines.append("}")
    lines.append("")
    lines.append("export const MANIFEST: ManifestEntry[] = [")

    for entry in entries:
        sql_file = MIGRATIONS / f"{entry['tag']}.sql"
        sql = sql_file.read_text(encoding="utf-8")
        lines.append("  {")
        lines.append(f"    idx: {entry['idx']},")
        lines.append(f"    tag: \"{entry['tag']}\",")
        lines.append("    sql: `")
        lines.append(ts_escape(sql))
        lines.append("    `,")
        lines.append("  },")

    lines.append("];")
    lines.append("")

    out = MIGRATIONS / "bundle.ts"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} with {len(entries)} migration(s)")


if __name__ == "__main__":
    main()